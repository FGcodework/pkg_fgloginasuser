#!/usr/bin/env bash
# Builds dist/pkg_fgloginasuser_vX.X.X.zip and regenerates updates.xml (the Joomla update server feed).
# The version is read from the manifests; the script stops if they disagree.
set -euo pipefail
cd "$(dirname "$0")"

ver() { sed -n 's:.*<version>\(.*\)</version>.*:\1:p' "$1" | head -1; }

VERSION=$(ver pkg_fgloginasuser.xml)
for f in com_fgloginasuser/fgloginasuser.xml plg_system_fgloginasuser/fgloginasuser.xml plg_actionlog_fgloginasuser/fgloginasuser.xml; do
  [ "$(ver "$f")" = "$VERSION" ] || { echo "Version mismatch: $f is $(ver "$f"), package is $VERSION" >&2; exit 1; }
done
for z in com_fgloginasuser plg_system_fgloginasuser plg_actionlog_fgloginasuser; do
  grep -q ">$z.zip<" pkg_fgloginasuser.xml || { echo "pkg_fgloginasuser.xml does not reference $z.zip" >&2; exit 1; }
done
grep -q "^## $VERSION - " CHANGELOG.md || { echo "CHANGELOG.md has no entry for $VERSION" >&2; exit 1; }

OUT="dist"
STAGE=$(mktemp -d)
mkdir -p "$OUT" "$STAGE/packages"
(cd com_fgloginasuser && zip -qr -X "$STAGE/packages/com_fgloginasuser.zip" . -x '*.DS_Store')
(cd plg_system_fgloginasuser && zip -qr -X "$STAGE/packages/plg_system_fgloginasuser.zip" . -x '*.DS_Store')
(cd plg_actionlog_fgloginasuser && zip -qr -X "$STAGE/packages/plg_actionlog_fgloginasuser.zip" . -x '*.DS_Store')
cp -r language script.php pkg_fgloginasuser.xml "$STAGE/"
ZIP="$OUT/pkg_fgloginasuser_v${VERSION}.zip"
rm -f "$ZIP"
(cd "$STAGE" && zip -qr -X "$OLDPWD/$ZIP" .)
rm -rf "$STAGE"

cat > updates.xml <<XML
<?xml version="1.0" encoding="utf-8"?>
<!-- Joomla update server for FG Login as User (package pkg_fgloginasuser).
     Generated by build.sh - do not edit by hand. -->
<updates>
    <update>
        <name>FG Login as User</name>
        <description>FG Login as User - log in as another user on the frontend or the backend (component + system plugin + action log plugin)</description>
        <element>pkg_fgloginasuser</element>
        <type>package</type>
        <version>${VERSION}</version>
        <client>site</client>
        <infourl title="FG Login as User ${VERSION}">https://github.com/FGcodework/pkg_fgloginasuser/releases/tag/v${VERSION}</infourl>
        <downloads>
            <downloadurl type="full" format="zip">https://github.com/FGcodework/pkg_fgloginasuser/releases/download/v${VERSION}/pkg_fgloginasuser_v${VERSION}.zip</downloadurl>
        </downloads>
        <tags>
            <tag>stable</tag>
        </tags>
        <maintainer>Fero</maintainer>
        <maintainerurl>https://github.com/FGcodework</maintainerurl>
        <targetplatform name="joomla" version="(5\.[4-9]|6\.[0-9]+)"/>
        <php_minimum>8.3</php_minimum>
    </update>
</updates>
XML
echo "$ZIP"
